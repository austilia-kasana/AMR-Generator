def _is_pure_monument_pack(root):
    """整个 mod 的内容只有：common/great_projects、gfx/interface/great_projects、
    interface/、localisation/，以及 descriptor·thumbnail"""
    for dirpath, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d != '.git']
        for f in fn:
            rel = os.path.relpath(os.path.join(dirpath, f), root).replace('/', '\\')
            low = rel.lower()
            if rel in MONUMENT_ONLY_OK or low.startswith('thumbnail') or rel.startswith('.git'):
                continue
            if (low.startswith('common\\great_projects')
                    or low.startswith('gfx\\interface\\great_projects')
                    or low.startswith('interface\\')
                    or low.startswith('localisation\\')):
                continue
            return False
    return True


