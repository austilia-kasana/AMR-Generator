def copy_pack_content(root, out):
    """把纯奇观包的 gfx / interface / localisation 抄进本 mod（同名文件不覆盖本 mod 自己的）"""
    n = 0
    for sub in ('gfx', 'interface', 'localisation'):
        src = os.path.join(root, sub)
        if not os.path.isdir(src):
            continue
        for dirpath, _dn, fn in os.walk(src):
            rel = os.path.relpath(dirpath, src)
            dst = os.path.join(out, sub) if rel == '.' else os.path.join(out, sub, rel)
            os.makedirs(dst, exist_ok=True)
            for f in fn:
                d = os.path.join(dst, f)
                if os.path.exists(d):
                    continue
                try:
                    shutil.copy2(os.path.join(dirpath, f), d)
                    n += 1
                except OSError:
                    pass
    return n


