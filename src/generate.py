def _pair_lines(cn, en, indent='  '):
    """把中文几行和英文几行按句配对（一句中文、紧跟一句英文）。

    说明文本里的这些"覆盖范围"备注是动态拼出来的，没法在模板里逐句翻译，
    只好在这里配对；行数不一致时，多出来的行整体接在后面。"""
    a = [x for x in cn.split('\n') if x.strip()]
    b = [x for x in en.split('\n') if x.strip()]
    out = []
    for i, x in enumerate(a):
        out.append(x)
        if i < len(b):
            out.append(indent + b[i].strip())
    out.extend(b[len(a):])
    return '\n'.join(out)


